import 'server-only';
import { prisma } from './db';
import { MENU_CATEGORIES } from './config';
import menuImages from '@/data/menu-images.json';
import menuImageMeta from '@/data/menu-image-meta.json';

// Data for the public customer menu (/menu). Only fields safe to show customers leave this module.

export type MenuCategory = (typeof MENU_CATEGORIES)[number];

export interface PublicMenuItem {
  id: string;
  name: string;
  description: string;
  featured: boolean;
  price: number | null;   // store (instore) price; null = not set yet
  image: string | null;   // photo in public/menu-photos/<slug>/, if one matches the name
  rim: { x: number; y: number } | null;  // where the price tag ties on, as fractions of the 2:3 photo frame
  blur: string | null;    // tiny data-URL preview shown while the photo loads
}

// Keep in sync with normalizeName() in scripts/gen-menu-images.mjs.
// Word order and "iced"/"hot"/"with" don't matter: "Iced-Mint-Latte" matches the menu "Latte Mint".
const IGNORED_WORDS = new Set(['iced', 'hot', 'with']);

export function normalizeName(s: string): string {
  return s.normalize('NFC').toLowerCase().replace(/&/g, ' and ')
    .split(/[^a-z0-9฀-๿]+/).filter(w => w && !IGNORED_WORDS.has(w)).sort().join('-');
}

const IMAGES = menuImages as Record<string, Record<string, string>>;

// Look in the category's own photo folder first, then any folder (a photo filed under the
// wrong category still shows up).
function findImage(slug: string, name: string): string | null {
  const key = normalizeName(name);
  return IMAGES[slug]?.[key] ?? Object.values(IMAGES).find(folder => folder[key])?.[key] ?? null;
}

const META = menuImageMeta as Record<string, { x: number; y: number; w: number; h: number; blur?: string | null }>;

// The photo is drawn object-contain + bottom-aligned in a 2:3 frame (see CupArt), so map the rim
// point from photo fractions to frame fractions the same way. Generated by scripts/gen-menu-image-meta.mjs.
function rimInFrame(image: string | null): { x: number; y: number } | null {
  const r = image ? META[image] : undefined;
  if (!r) return null;
  const FW = 2, FH = 3;
  const s = Math.min(FW / r.w, FH / r.h);
  const iw = r.w * s, ih = r.h * s;
  return { x: ((FW - iw) / 2 + r.x * iw) / FW, y: (FH - ih + r.y * ih) / FH };
}

function toPublicItem(
  r: { id: string; name: string; description: string; featured: boolean; sellPrice: unknown },
  slug: string,
): PublicMenuItem {
  const instore = (r.sellPrice as { instore?: number } | null)?.instore;
  const image = findImage(slug, r.name);
  return {
    id:          r.id,
    name:        r.name,
    description: r.description,
    featured:    r.featured,
    price:       instore && instore > 0 ? instore : null,
    image,
    rim:         rimInFrame(image),
    blur:        (image && META[image]?.blur) || null,
  };
}

// The "Best seller" page that opens the menu: every featured drink, whatever its category.
// Featured is the star toggle in the back office.
export const BEST_SELLER: MenuCategory = {
  name: 'Best seller', slug: 'best-seller', title: 'Best seller', tagline: 'เมนูขายดี ที่ลูกค้าสั่งบ่อยที่สุด',
};

// Best seller first (when anything is featured), then every category that has visible menus.
export async function getMenuPages(): Promise<{ category: MenuCategory; items: PublicMenuItem[] }[]> {
  const rows = await prisma.menu.findMany({
    where: { visible: true },
    orderBy: { createdAt: 'asc' },
    select: { id: true, name: true, description: true, category: true, featured: true, sellPrice: true },
  });
  const slugOf = (name: string) => MENU_CATEGORIES.find(c => c.name === name)?.slug ?? '';
  const order = (name: string) => MENU_CATEGORIES.findIndex(c => c.name === name);
  const bestSellers = rows.filter(r => r.featured)
    .sort((a, b) => order(a.category) - order(b.category))   // stable: same category keeps menu order
    .map(r => toPublicItem(r, slugOf(r.category)));
  const pages = MENU_CATEGORIES
    .map(category => ({ category, items: rows.filter(r => r.category === category.name).map(r => toPublicItem(r, category.slug)) }))
    .filter(page => page.items.length > 0);
  return bestSellers.length ? [{ category: BEST_SELLER, items: bestSellers }, ...pages] : pages;
}
